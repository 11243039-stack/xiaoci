// ปัญหาที่แก้: AI ตอบเรื่อง慈濟เองได้ แต่ถ้ามันไม่รู้จริง มันจะ "แต่งเรื่อง" ขึ้นมาเนียนๆ
// (เรียกว่า hallucination) เช่นแต่งชื่อวารสาร แต่งปีที่เกิดเหตุการณ์
// วิธีแก้ที่ใช้กันทั่วโลกคือ: ค้นเอกสารจริงก่อน → แปะข้อความจริงไปกับคำถาม → สั่งให้ตอบจากนั้น
//
// ไฟล์นี้ทำหน้าที่เดียว: รับข้อความที่คนพูด → คืน "ข้อความอ้างอิง" ให้ brain.js แปะไปกับคำถาม
// ถ้าคำถามไม่เกี่ยวกับ慈濟 หรือค้นไม่ได้ → คืนค่าว่าง แล้วหุ่นก็คุยตามปกติ (ห้ามพังทั้งระบบ)
//
// ยิงไปที่ไหน: https://harmony-ms-cmf.com/api/kb ของรุ่นพี่ — ยิงจากหน้าเว็บตรงๆ ได้เลย
//   ไม่ต้องมีรหัส ไม่ต้องมี server ของเรา (ฝั่งเขาซ่อนรหัสกับ agent server ไว้ให้หมดแล้ว)
//   ⚠️ เขาอนุญาตเฉพาะเว็บที่อยู่ในลิสต์: https://11243039-stack.github.io
//      → เว็บที่ขึ้นจริงใช้ได้  ·  เปิดจาก http://localhost ตอนพัฒนาจะโดน 403
//        (ถ้าอยากเทสในเครื่อง ต้องขอรุ่นพี่เติม localhost เข้าลิสต์)
//
// กติกาของ endpoint ที่ต้องเคารพ (ผิดข้อไหนก็ 400 หรือ 429 เปล่าๆ)
//   · query ยาวเกิน 200 ตัวอักษร → 400     ไฟล์นี้ตัดให้ก่อนส่ง
//   · top_k รับ 1-5 เท่านั้น               ไฟล์นี้หนีบให้
//   · ยิงได้ 20 ครั้ง/นาที ต่อ 1 IP → 429  ไฟล์นี้จำคำตอบเก่าไว้ ไม่ยิงซ้ำคำถามเดิม
//
// ไฟล์นี้แบ่งเป็น 4 ส่วน
//   ส่วนที่ 1  KEYWORDS + aboutTzuChi()  ด่านแรก: คำถามนี้เกี่ยวกับ慈濟ไหม
//   ส่วนที่ 2  snippet()/format()  ตัดข้อความดิบให้สั้นพอจะส่งให้ AI
//   ส่วนที่ 3  explain()  แปลรหัส error เป็นสาเหตุจริง
//   ส่วนที่ 4  makeCorpus()  ตัวที่ brain.js เอาไปใช้
//
// ทำไมต้องมีด่านแรก (ส่วนที่ 1) — สำคัญมาก:
//   API ตัวนี้ "คืนผลลัพธ์เสมอ" ไม่ว่าจะถามอะไร ไม่มีคำว่าหาไม่เจอ
//   และคะแนน (score) แยกเรื่องเกี่ยว/ไม่เกี่ยวไม่ได้เลย — ยิงจริงผ่าน /api/kb มาแล้ว:
//       「證嚴上人是誰」     (เกี่ยวเต็มๆ)      ได้ 0.69
//       「靜思語有哪些」     (เกี่ยวเต็มๆ)      ได้ 0.74
//       「今天晚餐吃什麼」   (ไม่เกี่ยวเลย)     ได้ 0.78  ← สูงกว่าสองอันบน
//       「竹筒歲月是什麼」   (เกี่ยวเต็มๆ)      ได้ 1.14
//   คือไม่มีเส้นไหนแบ่งได้ ตั้งสูงก็ทิ้งของดี ตั้งต่ำก็รับขยะ
//   → ด่านแรก (เช็คคำ) คือตัวตัดสินจริงว่าจะค้นไหม ส่วนคะแนนเหลือหน้าที่แค่ตัดขยะชัดๆ ทิ้ง
//   (ด่านแรกยังช่วยประหยัดโควตา 20 ครั้ง/นาที ด้วย — ทักทายเฉยๆ ไม่เสียโควตาเลย)
//
// ไม่ใช้ document/window เลย → ทดสอบด้วย node ได้เหมือน brain.js

export const KB_URL = 'https://harmony-ms-cmf.com/api/kb';
const MAX_QUERY = 200;   // ยาวกว่านี้ฝั่งเขาตอบ 400

// ---- ส่วนที่ 1: ด่านแรก — คำถามนี้เกี่ยวกับ慈濟ไหม ----------------------------------
// เติมคำใหม่ได้เรื่อยๆ ตรงนี้ (เจอคำที่ควรค้นแล้วไม่ค้น = เติมคำนั้นลงไป)
export const KEYWORDS = [
  '慈濟', '證嚴', '上人', '靜思', '精舍', '竹筒', '大愛', '志工', '慈青', '慈誠',
  '月刊', '花蓮', '環保', '回收', '賑災', '骨髓', '義診', '善款',
  '福慧', '無量義', '四大志業', '八大法印', '感恩', '知足', '善解', '包容',
  'tzu chi', 'jing si', 'cheng yen',   // เผื่อถามเป็นอังกฤษ (เทียบแบบไม่สนตัวพิมพ์)
];

export function aboutTzuChi(text) {
  const s = String(text || '').toLowerCase();
  return KEYWORDS.some((word) => s.includes(word.toLowerCase()));
}

// ---- ส่วนที่ 2: ตัดข้อความดิบให้พอดีคำ ----------------------------------------------
// ข้อความที่ได้มาเป็นชิ้นดิบ 400-3000 ตัวอักษร มีขึ้นบรรทัดใหม่ปนตารางปน
// ส่งทั้งก้อนให้ AI = ช้าและเปลืองเงิน เลยตัดให้เหลือเท่าที่จำเป็น
function snippet(text, limit) {
  const clean = String(text || '').replace(/\s+/g, ' ').trim();
  return clean.length > limit ? `${clean.slice(0, limit)}…` : clean;
}

function format(hits, perHit) {
  return hits
    .map((h, i) => `【${i + 1}】${snippet(h.text, perHit)}\n(出處：${h.document_name || '慈濟資料'})`)
    .join('\n\n');
}

// ---- ส่วนที่ 3: แปล error เป็นภาษาคน ------------------------------------------------
// ทั้งหมดนี้ไม่ทำให้หุ่นพัง แค่ขึ้นใน console ให้เรารู้ว่าเกิดอะไร
function explain(status) {
  return {
    400: 'คำถามผิดกติกา (ยาวเกิน 200 ตัวอักษร? top_k ไม่ใช่ตัวเลข?)',
    403: 'เว็บนี้ไม่ได้อยู่ในลิสต์ที่รุ่นพี่อนุญาต — เปิดจาก localhost จะเจออันนี้ ต้องขอเขาเติมลิสต์',
    429: 'ยิงถี่เกินไป (จำกัด 20 ครั้ง/นาที ต่อ 1 IP) เดี๋ยวค่อยถามใหม่',
  }[status] || `ค้นคลังไม่สำเร็จ (${status})`;
}

// ---- ส่วนที่ 4: ตัวที่เอาไปใช้จริง -------------------------------------------------
// makeCorpus() คืนฟังก์ชันตัวเดียว เรียกแล้วได้ข้อความอ้างอิง (หรือค่าว่าง)
//
//   endpoint  ที่อยู่ของ API (เปลี่ยนได้เวลาเทส)
//   minScore  ด่านที่สอง: ตัดขยะชัดๆ ทิ้ง — 0.65 มาจากคะแนนต่ำสุดของคำถามที่เกี่ยวจริง
//             ที่วัดได้ (0.69) ไม่ใช่ 1.1 ที่ฝั่ง Aura ใช้ ถ้าใช้ 1.1 คำถามอย่าง
//             「證嚴上人是誰」จะถูกทิ้งทั้งที่เอกสารที่ได้มาถูกต้อง
//   topK      ขอได้ 1-5
//   timeoutMs ของจริงวัดได้ 0.5-6.6 วิ (ตัวเลข 0.08-0.39 วิ ในเอกสารคือวัดในวงเดียวกับ
//             agent server ไม่ใช่ผ่านเน็ต) ตั้ง 8 วิเพื่อไม่ให้ตัดทิ้งกลางคัน
//             แลกกับการที่หุ่นอาจเงียบนานขึ้น — ถ้ารู้สึกช้าไป ลดค่านี้ได้ หุ่นจะตอบ
//             โดยไม่มีเอกสารอ้างอิงแทน (ไม่พัง)
//   cacheSize จำคำถาม-คำตอบล่าสุดไว้กี่คำถาม (กันยิงซ้ำจนโดน 429)
export function makeCorpus(opts = {}) {
  const {
    endpoint = KB_URL,
    minScore = 0.65,
    topK = 3,
    timeoutMs = 8000,
    maxChars = 1200,       // ความยาวรวมของข้อความอ้างอิงที่ยอมส่งให้ AI
    cacheSize = 20,
  } = opts;
  const top_k = Math.max(1, Math.min(Math.round(topK), 5));
  const cache = new Map();   // คำถาม → ข้อความอ้างอิง (เก่าสุดหลุดออกเมื่อเต็ม)

  return async function lookup(text) {
    if (!aboutTzuChi(text)) return '';
    // เด็กพูดยาวได้เรื่อยๆ แต่ฝั่งเขารับ 200 ตัวอักษร เกินแล้วตัด ไม่ใช่ปล่อยให้ 400
    const query = String(text).trim().slice(0, MAX_QUERY);
    if (cache.has(query)) return cache.get(query);

    const abort = new AbortController();
    const timer = setTimeout(() => abort.abort(), timeoutMs);
    try {
      const res = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        signal: abort.signal,
        body: JSON.stringify({ query, top_k }),
      });
      if (!res.ok) throw new Error(explain(res.status));
      const data = await res.json();
      const hits = (data.results || [])
        .filter((h) => Number(h.score) >= minScore)
        .sort((a, b) => Number(b.score) - Number(a.score));
      // เอกสารเดียวกันมาได้หลายชิ้น เอาชิ้นคะแนนสูงสุดของแต่ละเอกสารพอ
      const seen = new Set();
      const picked = hits.filter((h) => !seen.has(h.document_name) && seen.add(h.document_name));
      const out = picked.length ? format(picked, Math.floor(maxChars / picked.length)) : '';
      // จำไว้ทั้งกรณีเจอและไม่เจอ — ถามซ้ำคำเดิมไม่ควรเสียโควตาอีกครั้ง
      if (cache.size >= cacheSize) cache.delete(cache.keys().next().value);
      cache.set(query, out);
      return out;
    } catch (err) {
      // ค้นไม่ได้ไม่ใช่เรื่องคอขาดบาดตาย — หุ่นตอบจากความรู้ตัวเองต่อไป
      console.warn('[corpus] ค้นคลังไม่ได้:', err.message);
      return '';
    } finally {
      clearTimeout(timer);
    }
  };
}
